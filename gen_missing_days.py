# ─── Helpers ───
def wrap(inner, tag, cls=None, style=None, extra=""):
    a = f' class="{cls}"' if cls else ""
    s = f' style="{style}"' if style else ""
    return f"<{tag}{a}{s}{extra}>{inner}</{tag}>"

def step(title, color, body, full=False):
    cls = "step full" if full else "step"
    return f'<div class="{cls}"><h4><span class="dot" style="background:{color}"></span>{title}</h4>{body}</div>'

def steps_container(children):
    return f'<div class="steps">{"".join(children)}</div>'

def h3_block(color_name, emoji, text):
    return f'<h3 style="color:var(--{color_name});border-bottom:2px solid var(--{color_name});padding-bottom:6px;margin:16px 0 12px">{emoji} {text}</h3>'

def q_block(n, q, a):
    return f'<div class="q-block"><span class="q-num">{n}.</span><span class="question">{q}</span><button class="ans-btn" onclick="showAns(this)">点击查看答案</button><div class="answer">{a}</div></div>'

def formula(eq, meaning):
    return f'<div class="formula"><div class="eq">{eq}</div><div class="meaning">{meaning}</div></div>'

def day_page(num, date_str, weekday, subjects_tag, goal, body_html, check_html):
    return f'''
<div class="day-page">
<div class="dtop"><div class="dnum">Day {num}</div><div class="dinfo"><div>{date_str} {weekday}</div><div style="font-size:12px">{subjects_tag}</div></div></div>
<div class="dbody">
<div class="goal"><b>🎯 今日目标</b>：{goal}</div>
{body_html}
<div class="check"><b>✔ 今日达标检查</b>（睡前逐条确认）：<br>{check_html}</div>
</div></div>
'''

G = f'style="color:var(--"{{color_name}}");border-bottom:2px solid var(--{{color_name}});padding-bottom:6px;margin:16px 0 12px">{{emoji}} {{text}}'

# ─── Content Data ───
# Each entry: (day_num, date, weekday, subjects_tag, goal, sections, check)
# sections: list of ("color_name", "emoji", "subject_text", [step_html_parts])
# each step_html part is (title, color, body, is_full)

def make_sections(*args):
    """args: alternating h3 tuples and steps tuples"""
    result = []
    i = 0
    while i < len(args):
        # h3: ("blue", "📖", "数学·xxx")
        h3_args = args[i]
        i += 1
        h3_html = f'<h3 style="color:var(--{h3_args[0]});border-bottom:2px solid var(--{h3_args[0]});padding-bottom:6px;margin:16px 0 12px">{h3_args[1]} {h3_args[2]}</h3>'
        # steps: list of (title, color, body, is_full)
        steps = args[i] if i < len(args) and isinstance(args[i], list) else []
        i += 1
        steps_html = steps_container([step(s[0], s[1], s[2], s[3] if len(s) > 3 else False) for s in steps])
        result.append(h3_html + steps_html)
    return "".join(result)


